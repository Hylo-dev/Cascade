/// PluginFontWeight mirrors SwiftUI's `Font.Weight`.
public enum PluginFontWeight: String, Codable, Hashable, Sendable {

    case ultraLight
    case thin
    case light
    case regular
    case medium
    case semibold
    case bold
    case heavy
    case black
}
